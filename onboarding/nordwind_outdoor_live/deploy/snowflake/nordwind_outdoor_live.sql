-- Production deploy definition for the nordwind_outdoor_live onboarding pipeline.
-- Run by the team's release after this branch is merged. The onboarding Mission never runs it.
-- <PRODUCTION_DATABASE>: the dev database ANALYTICS_DEMO_LIVE carries no development marker in its name,
-- so the production database is left for the team to set before running this file.

CREATE SCHEMA IF NOT EXISTS <PRODUCTION_DATABASE>.PIPELINES;

CREATE FILE FORMAT IF NOT EXISTS <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_CSV
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE STAGE IF NOT EXISTS <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_DROP
  URL = 's3://genesis-lab-data-730335510242/data-onboarding/nordwind-outdoor-live/'
  STORAGE_INTEGRATION = GENESIS_ONBOARDING_DEMO_S3;

CREATE GIT REPOSITORY IF NOT EXISTS <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_ONBOARDING_PIPELINES
  ORIGIN = 'https://github.com/genesis-computing-ai/nordwind-onboarding-pipelines'
  API_INTEGRATION = GENESIS_ONBOARDING_DEMO_GIT;

ALTER GIT REPOSITORY <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_PIPELINE_PROD
  FROM '@<PRODUCTION_DATABASE>.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor_live';

CREATE OR REPLACE TASK <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_DAILY_PROD
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_PIPELINE_PROD ARGS = 'build --target prod';

ALTER TASK <PRODUCTION_DATABASE>.PIPELINES.NORDWIND_OUTDOOR_LIVE_DAILY_PROD RESUME;

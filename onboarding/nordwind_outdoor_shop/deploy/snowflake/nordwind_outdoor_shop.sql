-- Production deploy definition for the Nordwind Outdoor Shop pipeline.
-- Run by the team's release after the pull request is merged; never run by the onboarding Mission.
-- Every object lives in the production database ANALYTICS, so production never depends on ANALYTICS_DEV.

CREATE SCHEMA IF NOT EXISTS ANALYTICS.PIPELINES;

CREATE FILE FORMAT IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_CSV
  TYPE = CSV
  RECORD_DELIMITER = '\n'
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = FALSE
  TRIM_SPACE = FALSE
  ESCAPE = NONE
  ESCAPE_UNENCLOSED_FIELD = '\\'
  NULL_IF = ('\\N')
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
  ENCODING = 'UTF8'
  SKIP_BYTE_ORDER_MARK = TRUE;

CREATE STAGE IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_DROP
  URL = 's3://genesis-lab-data-730335510242/data-onboarding/nordwind-outdoor-shop/'
  STORAGE_INTEGRATION = GENESIS_ONBOARDING_DEMO_S3;

CREATE GIT REPOSITORY IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES
  ORIGIN = 'https://github.com/genesis-computing-ai/nordwind-onboarding-pipelines'
  API_INTEGRATION = GENESIS_ONBOARDING_DEMO_GIT;

ALTER GIT REPOSITORY ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_PIPELINE_PROD
  FROM '@ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor_shop';

-- Daily at 06:00 Europe/Berlin: two hours after Nordwind's 04:00 export.
CREATE OR REPLACE TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_DAILY_PROD
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_PIPELINE_PROD ARGS = 'build --target prod';

ALTER TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_DAILY_PROD RESUME;

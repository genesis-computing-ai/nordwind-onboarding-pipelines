-- Production deploy definition for the Nordwind Outdoor 2 pipeline.
-- Run by the team's release after this branch is merged; never run by the onboarding Mission.
-- Everything lives in the production database ANALYTICS, so production keeps running whatever happens to ANALYTICS_DEV.

CREATE SCHEMA IF NOT EXISTS ANALYTICS.PIPELINES;

CREATE FILE FORMAT IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_CSV
  TYPE = CSV
  RECORD_DELIMITER = '\n'
  FIELD_DELIMITER = ','
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ESCAPE = NONE
  ESCAPE_UNENCLOSED_FIELD = '\\'
  TRIM_SPACE = FALSE
  NULL_IF = ('\\N')
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE
  EMPTY_FIELD_AS_NULL = FALSE
  SKIP_BYTE_ORDER_MARK = TRUE
  ENCODING = 'UTF8';

CREATE STAGE IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_DROP
  URL = 's3://genesis-lab-data-730335510242/data-onboarding/nordwind-outdoor/'
  STORAGE_INTEGRATION = GENESIS_ONBOARDING_DEMO_S3;

CREATE GIT REPOSITORY IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES
  ORIGIN = 'https://github.com/genesis-computing-ai/nordwind-onboarding-pipelines'
  API_INTEGRATION = GENESIS_ONBOARDING_DEMO_GIT;

ALTER GIT REPOSITORY ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_PIPELINE_PROD
  FROM '@ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor_2';

CREATE OR REPLACE TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_DAILY_PROD
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_PIPELINE_PROD ARGS = 'build --target prod';

ALTER TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_2_DAILY_PROD RESUME;

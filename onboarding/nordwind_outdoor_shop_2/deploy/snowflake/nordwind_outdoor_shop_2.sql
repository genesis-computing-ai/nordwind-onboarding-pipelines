-- Production deploy definition for the nordwind_outdoor_shop_2 pipeline.
-- Run by the team's release once the pull request is merged; never run by the onboarding Mission.
-- Everything lives in the production database ANALYTICS, so production keeps running whatever happens to ANALYTICS_DEV.
-- Review before running (Assumptions for review): the role GENESIS_SVC_ROLE and warehouse XSMALL, the storage
-- integration GENESIS_ONBOARDING_DEMO_S3, the API integration GENESIS_ONBOARDING_DEMO_GIT.

CREATE SCHEMA IF NOT EXISTS ANALYTICS.PIPELINES;

CREATE FILE FORMAT IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_CSV
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = FALSE;

CREATE STAGE IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_DROP
  URL = 's3://genesis-lab-data-730335510242/data-onboarding/nordwind-outdoor-shop/'
  STORAGE_INTEGRATION = GENESIS_ONBOARDING_DEMO_S3;

CREATE GIT REPOSITORY IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES
  ORIGIN = 'https://github.com/genesis-computing-ai/nordwind-onboarding-pipelines'
  API_INTEGRATION = GENESIS_ONBOARDING_DEMO_GIT;

ALTER GIT REPOSITORY ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_PIPELINE_PROD
  FROM '@ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor_shop_2';

-- Daily at 06:00 Berlin time: two hours after the shop's own 04:00 export.
CREATE OR REPLACE TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_DAILY_PROD
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_PIPELINE_PROD ARGS = 'build --target prod';

ALTER TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_SHOP_2_DAILY_PROD RESUME;

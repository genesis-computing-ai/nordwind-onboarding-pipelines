-- Production deploy definition for the nordwind_outdoor pipeline. Run by the team's release after this
-- branch is merged into the default branch; never run by the onboarding Mission.
-- Everything lives in ANALYTICS.PIPELINES and builds ANALYTICS.NORDWIND_OUTDOOR.ORDER_LINE.

CREATE SCHEMA IF NOT EXISTS ANALYTICS.PIPELINES;

CREATE FILE FORMAT IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_CSV
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE STAGE IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_DROP
  URL = 's3://genesis-lab-data-730335510242/data-onboarding/nordwind-outdoor/'
  STORAGE_INTEGRATION = GENESIS_ONBOARDING_DEMO_S3;

CREATE GIT REPOSITORY IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES
  ORIGIN = 'https://github.com/genesis-computing-ai/nordwind-onboarding-pipelines'
  API_INTEGRATION = GENESIS_ONBOARDING_DEMO_GIT;

ALTER GIT REPOSITORY ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_PIPELINE_PROD
  FROM '@ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor';

CREATE OR REPLACE TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_DAILY_PROD
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_PIPELINE_PROD ARGS = 'build --target prod';

ALTER TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_DAILY_PROD RESUME;

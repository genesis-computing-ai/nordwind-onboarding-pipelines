-- Production deploy definition for the nordwind_outdoor onboarding pipeline.
-- Run by the team's release after this branch is merged to main; never run by the onboarding Mission.
-- Assumptions for review: the role GENESIS_SVC_ROLE and the drop stage ANALYTICS_DEV.PIPELINES.NORDWIND_OUTDOOR_DROP
-- are the dev ones; set your release's role and stage before running.

CREATE FILE FORMAT IF NOT EXISTS ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_CSV
  TYPE = CSV FIELD_DELIMITER = ',' SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

ALTER GIT REPOSITORY ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES FETCH;

CREATE OR REPLACE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_PIPELINE
  FROM '@ANALYTICS.PIPELINES.NORDWIND_ONBOARDING_PIPELINES/branches/main/onboarding/nordwind_outdoor';

CREATE OR REPLACE TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_DAILY
  WAREHOUSE = XSMALL
  SCHEDULE = 'USING CRON 0 6 * * * Europe/Berlin'
  AS EXECUTE DBT PROJECT ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_PIPELINE ARGS = 'build --target prod';

ALTER TASK ANALYTICS.PIPELINES.NORDWIND_OUTDOOR_DAILY RESUME;
